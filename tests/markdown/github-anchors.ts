/**
 * Headings as GitHub anchors them, measured.
 *
 * Each document below was sent whole to GitHub's Markdown API
 * (`POST /markdown`, mode `markdown`) on 2026-11-12, as `## <heading>`
 * lines a blank line apart, and the `href` of each heading's permalink was
 * read back from the HTML it returned and percent-decoded. So each pair is a
 * heading and the anchor GitHub gave it in that document, where an earlier
 * heading of the same slug moves it to `-1`, `-2` and so on.
 *
 * The headings were chosen to reach every way the text GitHub renders can
 * differ from the text written: `_` in a word and around one, code spans,
 * links, images, tags, autolinks, character references, escapes, emphasis
 * beside punctuation, symbols and spaces of other scripts, and case. A
 * heading is written here with an escape for any character that does not
 * show.
 */

/** One document: its headings in order, each with GitHub's anchor. */
export interface AnchoredDocument {
  readonly headings: ReadonlyArray<readonly [heading: string, anchor: string]>;
  /** What follows the headings in the document sent: link definitions it reads. */
  readonly tail: string;
}

